const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const source = fs.readFileSync('board/server.py', 'utf8').replace(/\r\n/g, '\n');
const code = source.match(/function actionsHtml\(\) \{[\s\S]*?\n\}\n\nfunction renderActions/)[0].replace(/\n\nfunction renderActions$/, '');
const ctx = {WRITABLE: true, BUSY: false, FORM_OPEN: false, DRAFT_COMMENT: '', escHtml: s => s};
vm.createContext(ctx);
vm.runInContext(code, ctx);
ctx.CARD = {agent: true, mergePending: true, pr: 'https://example.com/pr/1'};
let html = ctx.actionsHtml();
assert(html.includes('批准合并') && html.includes('查看 PR') && html.includes('<details>') && html.includes('暂停自动处理'));
assert(html.includes('暂停后不会自动合并'));
ctx.CARD = {agent: true, state: 'running'};
html = ctx.actionsHtml();
assert(html.includes('转人工处理') && !html.includes('暂停自动处理'));
ctx.CARD = {paused: true};
assert(ctx.actionsHtml().includes('恢复执行'));
ctx.CARD = {agent: true, mergePending: true, approved: true};
assert(ctx.actionsHtml().includes('撤销批准'));
console.log('看板操作：待合并、执行中、暂停和已批准均通过');
